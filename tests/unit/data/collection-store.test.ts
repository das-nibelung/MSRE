import { IMAGE_OCCLUSION_NOTE_TYPE_ID } from "src/data/collection/builtin-note-types";
import {
    CollectionStorage,
    CollectionStore,
    DEFAULT_DECK_OPTIONS_ID,
    formatCollection,
    mergeCollections,
    migrateCollection,
    parseCollection,
} from "src/data/collection/collection-store";

class MemoryStorage implements CollectionStorage {
    collection: string | null = null;
    reviews: string | null = null;

    readCollection(): Promise<string | null> {
        return Promise.resolve(this.collection);
    }

    writeCollection(content: string): Promise<void> {
        this.collection = content;
        return Promise.resolve();
    }

    readReviewLog(): Promise<string | null> {
        return Promise.resolve(this.reviews);
    }

    writeReviewLog(content: string): Promise<void> {
        this.reviews = content;
        return Promise.resolve();
    }
}

describe("Anki-style collection store", () => {
    let nextId = 0;
    const idFactory = (prefix: string): string => `${prefix}-${++nextId}`;

    beforeEach(() => {
        nextId = 0;
    });

    it("stores one note separately from cards generated by its templates", async () => {
        const storage = new MemoryStorage();
        const store = new CollectionStore(storage, () => 100, idFactory);

        const note = await store.createNativeNote({
            type: "reversed",
            front: "bonjour",
            back: "hello",
            answerMode: "type",
            deckPath: "Languages/French",
            sourcePath: "Spaced Repetition/Cards/Languages/bonjour.md",
            questionId: "^sr-data-id-note-1",
        });

        const snapshot = store.getCollectionSnapshot();
        const cards = Object.values(snapshot.cards).filter((card) => card.noteId === note.id);
        expect(note.fields).toEqual({ front: "bonjour", back: "hello" });
        expect(note.answerMode).toBe("type");
        expect(cards).toHaveLength(2);
        expect(cards.map((card) => card.ordinal)).toEqual([0, 1]);
        expect(cards.map((card) => card.legacyStableId)).toEqual([
            "^sr-data-id-note-1:0",
            "^sr-data-id-note-1:1",
        ]);
        expect(snapshot.decks[cards[0].deckId].name).toBe("Languages/French");
        expect(parseCollection(storage.collection).notes[note.id]).toBeDefined();
    });

    it("supports custom note fields, templates, and multiple cloze siblings", async () => {
        const storage = new MemoryStorage();
        const store = new CollectionStore(storage, () => 150, idFactory);
        await store.saveNoteType({
            id: "medical-cloze",
            name: "Medical cloze",
            kind: "cloze",
            fields: [
                {
                    id: "statement",
                    name: "Statement",
                    ordinal: 0,
                    kind: "rich-text",
                    required: true,
                },
                { id: "source", name: "Source", ordinal: 1, kind: "text", required: false },
            ],
            templates: [
                {
                    id: "medical-cloze-card",
                    name: "Recall",
                    ordinal: 0,
                    questionFormat: "{{cloze:statement}}",
                    answerFormat: "{{cloze:statement}}<hr>{{source}}",
                    deckOverride: null,
                    enabled: true,
                },
            ],
            css: ".card { font-size: 20px; }",
        });

        const note = await store.createNote({
            noteTypeId: "medical-cloze",
            fields: {
                statement: "{{c1::Aspirin}} inhibits {{c2::COX}}.",
                source: "Pharmacology",
            },
            tags: ["#medicine", "medicine", " exam "],
            deckPath: "Medicine/Pharmacology",
            source: { kind: "managed", path: "Cards/aspirin.md", questionId: "^aspirin" },
        });

        const snapshot = store.getCollectionSnapshot();
        const cards = Object.values(snapshot.cards).filter((card) => card.noteId === note.id);
        expect(cards.map((card) => card.ordinal)).toEqual([0, 1]);
        expect(note.tags).toEqual(["exam", "medicine"]);
        expect(snapshot.deckOptions["builtin-default-options"].desiredRetention).toBe(0.9);
    });

    it("keeps image occlusion siblings under one parent note", async () => {
        const store = new CollectionStore(new MemoryStorage(), () => 175, idFactory);
        const note = await store.createNote({
            noteTypeId: IMAGE_OCCLUSION_NOTE_TYPE_ID,
            fields: {
                source: "Media/anatomy.png",
                masks: JSON.stringify([
                    { id: "heart", x: 0.1, y: 0.2, width: 0.2, height: 0.1, label: "Heart" },
                    { id: "lung", x: 0.5, y: 0.2, width: 0.2, height: 0.2, label: "Lung" },
                ]),
                assets: "[]",
                mode: "hide-all",
            },
            deckPath: "Medicine/Anatomy",
            source: { kind: "managed", path: "Cards/anatomy.md", questionId: "^anatomy" },
            legacyQuestionIds: { 0: "^anatomy-1", 1: "^anatomy-2" },
        });

        const cards = Object.values(store.getCollectionSnapshot().cards).filter(
            (card) => card.noteId === note.id && !card.deletedAt,
        );
        expect(cards).toHaveLength(2);
        expect(cards.map((card) => card.legacyStableId)).toEqual(["^anatomy-1:0", "^anatomy-2:0"]);
    });

    it("keeps review history linked to stable note and card ids", async () => {
        const storage = new MemoryStorage();
        const store = new CollectionStore(storage, () => 200, idFactory);
        await store.createNativeNote({
            id: "note-fixed",
            type: "basic",
            front: "Q",
            back: "A",
            deckPath: "Law",
            sourcePath: "Cards/q.md",
            questionId: "^sr-data-id-note-fixed",
        });

        const reviewId = await store.recordReview({
            sourcePath: "Cards/q.md",
            questionId: "^sr-data-id-note-fixed",
            ordinal: 0,
            deckPath: "Law",
            front: "Q",
            back: "A",
            rating: 3,
            reviewedAt: 210,
            previousSchedule: null,
            nextSchedule: null,
        });

        const review = store.getReviewLogSnapshot().entries[reviewId];
        expect(review.noteId).toBe("note-fixed");
        expect(store.getCollectionSnapshot().cards[review.cardId]).toBeDefined();
        expect(review.rating).toBe(3);

        await store.removeReview(reviewId);
        expect(store.getReviewLogSnapshot().entries[reviewId].deletedAt).toBe(200);
    });

    it("lazily imports legacy Markdown cards when they are reviewed", async () => {
        const storage = new MemoryStorage();
        const store = new CollectionStore(storage, () => 300, idFactory);

        await store.recordReview({
            sourcePath: "Old cards.md",
            questionId: "^legacy-id",
            ordinal: 0,
            deckPath: "flashcards/Old",
            front: "Old question",
            back: "Old answer",
            rating: 2,
            previousSchedule: null,
            nextSchedule: null,
        });

        const snapshot = store.getCollectionSnapshot();
        const note = Object.values(snapshot.notes)[0];
        const card = Object.values(snapshot.cards)[0];
        expect(note.source).toEqual({
            kind: "markdown",
            path: "Old cards.md",
            questionId: "^legacy-id",
        });
        expect(card.legacyStableId).toBe("^legacy-id:0");
    });

    it("persists suspend and timed bury states and restores expired cards", async () => {
        let timestamp = 320;
        const storage = new MemoryStorage();
        const store = new CollectionStore(storage, () => timestamp, idFactory);
        const input = {
            sourcePath: "Cards/state.md",
            questionId: "^state-id",
            ordinal: 0,
            deckPath: "Medicine",
            front: "Question",
            back: "Answer",
        };

        await store.setLegacyCardsState([input], "suspended");
        expect(store.isLegacyCardReviewable("^state-id:0")).toBe(false);
        expect(store.getCardByLegacyStableId("^state-id:0")?.buriedUntil).toBeNull();
        await store.setLegacyCardsFlag([input], 4);
        expect(store.getCardByLegacyStableId("^state-id:0")?.flag).toBe(4);

        await store.setLegacyCardsState([input], "buried", 400);
        expect(store.isLegacyCardReviewable("^state-id:0", 399)).toBe(false);
        expect(store.isLegacyCardReviewable("^state-id:0", 400)).toBe(true);
        expect(await store.restoreExpiredBuriedCards(399)).toBe(0);

        timestamp = 400;
        expect(await store.restoreExpiredBuriedCards()).toBe(1);
        expect(store.getCardByLegacyStableId("^state-id:0")?.state).toBe("active");
        expect(store.isLegacyCardReviewable("^state-id:0")).toBe(true);
        expect(Object.values(parseCollection(storage.collection).cards)[0].state).toBe("active");
    });

    it("tracks source renames and tombstones notes with their sibling cards", async () => {
        const store = new CollectionStore(new MemoryStorage(), () => 350, idFactory);
        const note = await store.createNativeNote({
            type: "reversed",
            front: "front",
            back: "back",
            deckPath: "Deck",
            sourcePath: "Cards/old.md",
            questionId: "^note",
        });

        await store.renameSourcePath("Cards/old.md", "Cards/new.md");
        expect(store.findNoteBySource("Cards/new.md", "^note")?.id).toBe(note.id);
        await store.deleteNoteBySource("Cards/new.md", "^note");

        const snapshot = store.getCollectionSnapshot();
        expect(snapshot.notes[note.id].deletedAt).toBe(350);
        expect(
            Object.values(snapshot.cards)
                .filter((card) => card.noteId === note.id)
                .every((card) => card.deletedAt === 350),
        ).toBe(true);
    });

    it("uses independent scheduling ids for custom standard templates", async () => {
        const store = new CollectionStore(new MemoryStorage(), () => 375, idFactory);
        await store.saveNoteType({
            id: "custom-two-card",
            name: "Two card",
            kind: "standard",
            fields: [
                { id: "term", name: "Term", ordinal: 0, kind: "text", required: true },
                { id: "meaning", name: "Meaning", ordinal: 1, kind: "text", required: true },
            ],
            templates: [
                {
                    id: "forward",
                    name: "Forward",
                    ordinal: 0,
                    questionFormat: "{{Term}}",
                    answerFormat: "{{Meaning}}",
                    deckOverride: null,
                    enabled: true,
                },
                {
                    id: "backward",
                    name: "Backward",
                    ordinal: 1,
                    questionFormat: "{{Meaning}}",
                    answerFormat: "{{Term}}",
                    deckOverride: null,
                    enabled: true,
                },
            ],
            css: "",
        });
        const note = await store.createNote({
            noteTypeId: "custom-two-card",
            fields: { term: "ratio", meaning: "отношение" },
            deckPath: "Math",
            source: { kind: "managed", path: "ratio.md", questionId: "^note" },
            legacyQuestionIds: { 0: "^question-1", 1: "^question-2" },
        });

        const cards = Object.values(store.getCollectionSnapshot().cards).filter(
            (card) => card.noteId === note.id,
        );
        expect(cards.map((card) => card.legacyStableId)).toEqual([
            "^question-1:0",
            "^question-2:0",
        ]);
        await store.updateNote(note.id, {
            fields: { term: "proportion", meaning: "пропорция" },
            deckPath: "Math",
            source: { kind: "managed", path: "ratio.md", questionId: "^note" },
            legacyQuestionIds: { 0: "^question-1", 1: "^question-2" },
        });
        expect(store.getCollectionSnapshot().notes[note.id].fields.term).toBe("proportion");
        await expect(store.deleteNoteType("custom-two-card")).rejects.toThrow("note-type-in-use");
    });

    it("shares validated option presets across decks", async () => {
        const store = new CollectionStore(new MemoryStorage(), () => 390, idFactory);
        await store.ensureDeckPath("Medicine/Cardiology");
        await store.ensureDeckPath("Medicine/Neurology");
        const preset = await store.saveDeckOptions({
            id: "deck-options-intensive",
            name: " Intensive ",
            newCardsPerDay: 35,
            reviewsPerDay: 350,
            desiredRetention: 0.94,
            newCardOrder: "random",
        });
        await store.updateDeck("Medicine/Cardiology", {
            description: " High-yield cases ",
            optionsId: preset.id,
        });
        await store.updateDeck("Medicine/Neurology", { optionsId: preset.id });

        expect(store.getDeckOptionsForPath("Medicine/Cardiology")).toEqual(
            expect.objectContaining({
                name: "Intensive",
                newCardsPerDay: 35,
                desiredRetention: 0.94,
                newCardOrder: "random",
            }),
        );
        expect(store.getDeck("Medicine/Cardiology")?.description).toBe("High-yield cases");
        expect(store.countDecksForOptions(preset.id)).toBe(2);
        await expect(store.deleteDeckOptions(preset.id)).rejects.toThrow("deck-options-in-use");

        await store.updateDeck("Medicine/Cardiology", { optionsId: DEFAULT_DECK_OPTIONS_ID });
        await store.updateDeck("Medicine/Neurology", { optionsId: DEFAULT_DECK_OPTIONS_ID });
        await store.deleteDeckOptions(preset.id);
        expect(store.getDeckOptionsById(preset.id)).toBeNull();
    });

    it("rejects invalid deck option limits", async () => {
        const store = new CollectionStore(new MemoryStorage(), () => 395, idFactory);
        expect(store.getDeck("Missing")).toBeNull();
        expect(store.getDeckOptionsById("missing")).toBeNull();
        expect(store.getDeckOptionsForPath("Missing").id).toBe(DEFAULT_DECK_OPTIONS_ID);
        await expect(
            store.saveDeckOptions({
                id: "invalid-options",
                name: "Invalid",
                newCardsPerDay: -1,
                reviewsPerDay: 100,
                desiredRetention: 0.9,
                newCardOrder: "sequential",
            }),
        ).rejects.toThrow("invalid-new-card-limit");
        await expect(
            store.saveDeckOptions({
                id: "invalid-reviews",
                name: "Invalid",
                newCardsPerDay: 10,
                reviewsPerDay: -1,
                desiredRetention: 0.9,
                newCardOrder: "sequential",
            }),
        ).rejects.toThrow("invalid-review-limit");
        await expect(
            store.saveDeckOptions({
                id: "invalid-retention",
                name: "Invalid",
                newCardsPerDay: 10,
                reviewsPerDay: 100,
                desiredRetention: 0.5,
                newCardOrder: "sequential",
            }),
        ).rejects.toThrow("invalid-desired-retention");
        await expect(
            store.saveDeckOptions({
                id: "empty-name",
                name: " ",
                newCardsPerDay: 10,
                reviewsPerDay: 100,
                desiredRetention: 0.9,
                newCardOrder: "sequential",
            }),
        ).rejects.toThrow("deck-options-name-required");
        await expect(store.updateDeck("Medicine", { optionsId: "missing" })).rejects.toThrow(
            "deck-options-not-found",
        );
        await expect(store.deleteDeckOptions(DEFAULT_DECK_OPTIONS_ID)).rejects.toThrow(
            "builtin-deck-options",
        );
        await expect(store.deleteDeckOptions("missing")).resolves.toBeUndefined();
    });

    it("updates an existing preset without changing its creation timestamp", async () => {
        let timestamp = 400;
        const store = new CollectionStore(new MemoryStorage(), () => timestamp, idFactory);
        const original = await store.saveDeckOptions({
            id: "deck-options-shared",
            name: "Shared",
            newCardsPerDay: 20,
            reviewsPerDay: 200,
            desiredRetention: 0.9,
            newCardOrder: "sequential",
        });
        timestamp = 410;
        const updated = await store.saveDeckOptions({
            ...original,
            name: "Shared updated",
            reviewsPerDay: 250,
        });

        expect(updated.createdAt).toBe(400);
        expect(updated.updatedAt).toBe(410);
        expect(store.getDeckOptions().map((options) => options.name)).toEqual([
            "Default",
            "Shared updated",
        ]);
        await store.ensureDeckPath("Zoology");
        await store.ensureDeckPath("Anatomy");
        expect(store.getDecks().map((deck) => deck.name)).toEqual(["Anatomy", "Zoology"]);
        await store.updateDeck("Anatomy", { description: "Body structures" });
        expect(store.getDeck("Anatomy")?.optionsId).toBe(DEFAULT_DECK_OPTIONS_ID);
        await store.deleteDeckOptions(updated.id);
        expect(store.getDeckOptionsById(updated.id)).toBeNull();
    });

    it("migrates preview data and resolves sync conflicts per entity", () => {
        const older = migrateCollection({
            version: 0,
            notes: {
                n1: {
                    id: "n1",
                    noteTypeId: "builtin-basic",
                    fields: { front: "old" },
                    tags: [],
                    source: { kind: "managed", path: "a.md", questionId: null },
                    createdAt: 1,
                    updatedAt: 1,
                },
            },
            cards: {
                c1: {
                    id: "c1",
                    noteId: "n1",
                    templateId: "builtin-basic-card",
                    ordinal: 0,
                    deckId: "builtin-default-deck",
                    deckPath: "",
                    state: "active",
                    queue: "new",
                    schedule: null,
                    reps: 0,
                    lapses: 0,
                    lastReviewAt: null,
                    legacyStableId: "^n1:0",
                    createdAt: 1,
                    updatedAt: 1,
                },
            },
        });
        const newer = parseCollection(formatCollection(older));
        newer.notes.n1.fields.front = "new";
        newer.notes.n1.updatedAt = 2;

        const merged = mergeCollections(older, newer);
        expect(merged.schemaVersion).toBe(4);
        expect(merged.notes.n1.fields.front).toBe("new");
        expect(merged.cards.c1.buriedUntil).toBeNull();
        expect(merged.cards.c1.flag).toBe(0);
        expect(Object.keys(merged.noteTypes)).toEqual(
            expect.arrayContaining([
                "builtin-basic",
                "builtin-basic-and-reversed",
                "builtin-cloze",
            ]),
        );
    });
});
